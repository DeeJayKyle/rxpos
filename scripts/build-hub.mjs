// The self-hosted hub's copy of the cloud code (workplan step 16): worker/index.js and everything it imports (src/
// rules, the catalog) bundled into ONE file, server/hub-core.mjs, so the Windows app (`RxPOS.exe --hub`) and the hub
// download (RxPOS-Hub.zip) need nothing installed. Run by `npm run build` (vite.config.js); server/hub.mjs uses the
// bundle when it is there, else worker/ straight from a source checkout.
//   node scripts/build-hub.mjs
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export async function buildHub() {
  await build({
    entryPoints: [path.join(root, 'worker', 'index.js')],
    outfile: path.join(root, 'server', 'hub-core.mjs'),
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node22',
    // Turso is never used on a hub (its own SQLite file is): a stand-in so the Turso client isn't bundled
    plugins: [{
      name: 'no-turso',
      setup(b) {
        b.onResolve({ filter: /^@libsql\/client/ }, () => ({ path: 'no-turso', namespace: 'rxpos-stub' }));
        b.onLoad({ filter: /.*/, namespace: 'rxpos-stub' }, () => ({ contents: 'export function createClient() { throw new Error("Turso is not used on a hub"); }', loader: 'js' }));
      },
    }],
    banner: { js: '// Generated by scripts/build-hub.mjs from worker/index.js: do not edit.' },
    legalComments: 'none',
    logLevel: 'warning',
  });
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await buildHub();
