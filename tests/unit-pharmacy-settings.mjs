import assert from 'node:assert/strict';
import { pharmacyDefaults, pharmacyChanged, editOverrides, overrideKey, readOverrides, writeOverrides, settingsEqual, validatePharmacyDefaults } from '../src/pharmacy-settings.js';
const values = new Map();
globalThis.localStorage = { getItem:k=>values.get(k)||null, setItem:(k,v)=>values.set(k,v), removeItem:k=>values.delete(k) };
const shared = { ...pharmacyDefaults(), name:'Owner Pharmacy', phone:'0700000000', taxRate:18 };
const local = editOverrides(shared,shared,{...shared,name:'Local Till',taxRate:0});
assert.deepEqual(local,{name:'Local Till',taxRate:0});
assert.equal(shared.name,'Owner Pharmacy');
const a=overrideKey('https://cloud','a'), b=overrideKey('https://cloud','b');
writeOverrides(a,local);
assert.deepEqual(readOverrides(a),local);
assert.deepEqual(readOverrides(b),{});
assert.deepEqual(readOverrides(overrideKey('https://other-cloud','a')),{});
const changedOwner={...shared,phone:'0711111111',name:'New Owner Name'};
const effective={...changedOwner,...readOverrides(a)};
assert.equal(effective.name,'Local Till');
assert.equal(effective.phone,'0711111111');
assert.deepEqual(editOverrides(changedOwner,effective,{...effective,receiptFooter:'Other preference'},local),local);
assert.deepEqual(editOverrides(changedOwner,effective,{...effective,name:changedOwner.name},local),{taxRate:0});
writeOverrides(a,{});
assert.equal(({...changedOwner,...readOverrides(a)}).name,'New Owner Name');
assert.ok(pharmacyChanged(shared,{...shared,name:'Bad global edit'}));
assert.ok(!pharmacyChanged(shared,{...shared,receiptFooter:'Allowed shared preference'}));
assert.ok(settingsEqual({...shared},{...Object.fromEntries(Object.entries(shared).reverse())}));
assert.throws(()=>validatePharmacyDefaults({...shared,taxRate:-1}));
assert.equal(validatePharmacyDefaults({...shared,decimals:'2'}).decimals,2);
console.log('PASS device/cloud/tenant isolation, zero values, owner refresh, reset and shared-write protection');
